class I18n(QObject):
    changed = Signal()

    def __init__(self, lang="en"):
        super().__init__()
        self.lang = lang if lang in STRINGS else "en"

    def set_language(self, lang):
        if lang not in STRINGS or lang == self.lang:
            return
        self.lang = lang
        self.changed.emit()

    def t(self, key, **kwargs):
        s = STRINGS.get(self.lang, {}).get(key) or STRINGS["en"].get(key, key)
        return s.format(**kwargs) if kwargs else s


def detect_system_language():
    code = QLocale.system().name().split("_")[0].lower()
    return code if code in STRINGS else "en"


manager = I18n(detect_system_language())
